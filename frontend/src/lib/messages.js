/** First supported language among the candidates (URL, saved choice, deployment default), else English. */
export function pickLanguage(...candidates) {
  return candidates.find((c) => LANGUAGES.includes(c)) || DEFAULT_LANGUAGE
}

/** `translate('fr', 'answer.excerpts', { count: 2 })` -> "2 extraits". Unknown keys fall back to English, then to the key. */
export function translate(lang, key, vars = {}) {
  const dict = MESSAGES[lang] || MESSAGES[DEFAULT_LANGUAGE]
  let msg
  if (typeof vars.count === 'number') {
    const form = new Intl.PluralRules(lang).select(vars.count)
    msg = dict[`${key}_${form}`] ?? dict[`${key}_other`] ?? MESSAGES.en[`${key}_other`]
  }
  msg = msg ?? dict[key] ?? MESSAGES.en[key] ?? key
  return msg.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m))
}
